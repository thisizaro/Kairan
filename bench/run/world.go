type opts struct {
	root   string // repository root
	out    string // bench/out
	runs   int
	reuse  bool // a compose stack is already up (do not build or tear down)
	keep   bool
	only   map[string]bool
	rounds int
}

func (o *opts) want(name string) bool { return len(o.only) == 0 || o.only[name] }

// ---- the compose stack's secrets (generated by deploy/compose/demo.sh, gitignored) ----

type world struct {
	o          *opts
	run        string
	adminToken string
	keys       map[string]ed25519.PrivateKey
	pubs       []string
	cp         *cpc
}

func (o *opts) loadWorld() (*world, error) {
	w := &world{o: o, run: filepath.Join(o.root, "deploy", "compose", ".run"), keys: map[string]ed25519.PrivateKey{}}
	tok, err := os.ReadFile(filepath.Join(w.run, "admin.token"))
	if err != nil {
		return nil, err
	}
	w.adminToken = strings.TrimSpace(string(tok))
	for _, n := range []string{"admin-a", "admin-b", "admin-c"} {
		b, err := os.ReadFile(filepath.Join(w.run, "keys", n+".key"))
		if err != nil {
			return nil, err
		}
		seed, err := hex.DecodeString(strings.TrimSpace(string(b)))
		if err != nil || len(seed) != ed25519.SeedSize {
			return nil, fmt.Errorf("key %s: not a hex ed25519 seed", n)
		}
		w.keys[n] = ed25519.NewKeyFromSeed(seed)
	}
	pb, err := os.ReadFile(filepath.Join(w.run, "trusted-keys.json"))
	if err != nil {
		return nil, err
	}
	if err := json.Unmarshal(pb, &w.pubs); err != nil {
		return nil, err
	}
	w.cp = newCP(cpURL, w.adminToken)
	return w, nil
}

// ---- control plane client ----

type cpc struct {
	base, token string
	hc          *http.Client
	mu          sync.Mutex
	ver         map[string]uint64
}

func newCP(base, token string) *cpc {
	return &cpc{base: base, token: token, hc: &http.Client{Timeout: 30 * time.Second}, ver: map[string]uint64{}}
}

func (c *cpc) do(method, path string, body, out any) (int, wire.ErrorCode, error) {
	var rd io.Reader
	if body != nil {
		b, err := json.Marshal(body)
		if err != nil {
			return 0, "", err
		}
		rd = bytes.NewReader(b)
	}
	req, err := http.NewRequest(method, c.base+path, rd)
	if err != nil {
		return 0, "", err
	}
	req.Header.Set(wire.HeaderAuthorization, wire.BearerPrefix+c.token)
	if body != nil {
		req.Header.Set("Content-Type", wire.ContentTypeJSON)
	}
	res, err := c.hc.Do(req)
	if err != nil {
		return 0, "", err
	}
	defer res.Body.Close()
	data, _ := io.ReadAll(io.LimitReader(res.Body, 32<<20))
	if res.StatusCode/100 != 2 {
		var er wire.ErrorResponse
		_ = json.Unmarshal(data, &er)
		return res.StatusCode, er.Code, nil
	}
	if out != nil {
		if err := json.Unmarshal(data, out); err != nil {
			return res.StatusCode, "", fmt.Errorf("decode %s: %w", path, err)
		}
	}
	return res.StatusCode, "", nil
}

func (c *cpc) fleet(tenant string) (wire.FleetView, error) {
	var fv wire.FleetView
	code, ec, err := c.do("GET", wire.PathFleet+"?tenant="+tenant, nil, &fv)
	if err == nil && code != 200 {
		err = fmt.Errorf("fleet %s: HTTP %d %s", tenant, code, ec)
	}
	return fv, err
}

func (c *cpc) timeline(tenant string) (wire.TimelineView, error) {
	var tv wire.TimelineView
	code, ec, err := c.do("GET", wire.PathTimeline+"?tenant="+tenant, nil, &tv)
	if err == nil && code != 200 {
		err = fmt.Errorf("timeline %s: HTTP %d %s", tenant, code, ec)
	}
	return tv, err
}

// firstSeen returns, per proxy, the control-plane time (unix ms) at which it first reported version v.
func (c *cpc) firstSeen(tenant string, v uint64) (map[string]int64, error) {
	tv, err := c.timeline(tenant)
	if err != nil {
		return nil, err
	}
	out := map[string]int64{}
	for _, e := range tv.Entries {
		if e.Version == v {
			out[string(e.ProxyID)] = e.FirstSeenUnixMs
		}
	}
	return out, nil
}

// ---- policies ----

func payload(tenant string, version uint64) []byte {
	sales := map[string]string{"notes.read": "R", "crm.read_*": "R"}
	if version >= 2 {
		sales["notes.write"] = "W"
	}
	doc := map[string]any{
		"tenant": tenant, "version": version,
		"issued_at":  time.Now().Add(-time.Minute).UTC().Format(time.RFC3339),
		"expires_at": time.Now().Add(72 * time.Hour).UTC().Format(time.RFC3339),
		"default":    "deny",
		"roles":      map[string]any{"sales": sales, "intern": map[string]string{"notes.read": "R"}},
	}
	b, _ := json.Marshal(doc)
	return b
}

func (w *world) envelope(p []byte, signers ...string) wire.Envelope {
	env := wire.Envelope{PayloadType: wire.PayloadTypePolicy, Payload: p, Signatures: []wire.Signature{}}
	for _, s := range signers {
		trust.Sign(&env, w.keys[s])
	}
	return env
}

// syncVersion makes the counter for tenant continue from what the control plane already has.
func (c *cpc) syncVersion(tenant string) {
	var rv wire.RolloutView
	if code, _, _ := c.do("GET", wire.PathRollouts+"?tenant="+tenant, nil, &rv); code == 200 {
		c.mu.Lock()
		c.ver[tenant] = rv.Version
		c.mu.Unlock()
	}
}

// release publishes the next version of tenant with two signatures and starts a canary rollout. It returns the
// version and the host time taken just before the publish request.
func (w *world) release(c *cpc, tenant string, dwell uint64) (uint64, time.Time, error) {
	c.mu.Lock()
	c.ver[tenant]++
	v := c.ver[tenant]
	c.mu.Unlock()
	t0 := time.Now()
	code, ec, err := c.do("POST", wire.PathPolicies, w.envelope(payload(tenant, v), "admin-a", "admin-b"), nil)
	if err != nil || code/100 != 2 {
		return v, t0, fmt.Errorf("publish %s v%d: HTTP %d %s %v", tenant, v, code, ec, err)
	}
	code, ec, err = c.do("POST", wire.PathRollouts, wire.RolloutRequest{Tenant: wire.ID(tenant), Version: v, CanaryDwellSeconds: dwell}, nil)
	if err != nil || code/100 != 2 {
		return v, t0, fmt.Errorf("rollout %s v%d: HTTP %d %s %v", tenant, v, code, ec, err)
	}
	return v, t0, nil
}

// ---- docker ----

func docker(args ...string) (string, error) {
	ctx, cancel := context.WithTimeout(context.Background(), 150*time.Second)
	defer cancel()
	out, err := exec.CommandContext(ctx, "docker", args...).CombinedOutput()
	return strings.TrimSpace(string(out)), err
}

func mustDocker(args ...string) string {
	out, err := docker(args...)
	if err != nil {
		fatalf("docker %s: %v\n%s", strings.Join(args, " "), err, out)
	}
	return out
}

func fatalf(f string, a ...any) {
	fmt.Fprintf(os.Stderr, "bench: FATAL: "+f+"\n", a...)
	os.Exit(1)
}

func logf(f string, a ...any) { fmt.Printf("bench: "+f+"\n", a...) }

// waitFor polls f every `every` until it is true or limit passes (fatal then).
func waitFor(limit, every time.Duration, what string, f func() (bool, string)) time.Duration {
	start := time.Now()
	last := ""
	for {
		ok, d := f()
		if ok {
			return time.Since(start)
		}
		last = d
		if time.Since(start) > limit {
			fatalf("timed out after %v waiting for %s; last state: %s", limit, what, last)
		}
		time.Sleep(every)
	}
}

func ms(d time.Duration) float64 { return float64(d) / float64(time.Millisecond) }

func execOut(name string, args ...string) (string, error) {
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	out, err := exec.CommandContext(ctx, name, args...).Output()
	return string(out), err
}
